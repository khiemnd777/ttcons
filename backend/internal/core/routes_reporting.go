package core

import "github.com/gofiber/fiber/v2"

func registerReportingRoutes(protected fiber.Router, h *Handler) {
	protected.Get("/statistics/options", h.StatisticsOptions)
	protected.Get("/statistics/projects", h.ProjectStatistic)
	protected.Get("/statistics/projects/export", h.ProjectStatisticExport)
	protected.Get("/statistics/warehouse", h.WarehouseStatistic)
	protected.Get("/statistics/warehouse/export", h.WarehouseStatisticExport)
	protected.Get("/statistics/procurement", h.ProcurementStatistic)
	protected.Get("/statistics/procurement/export", h.ProcurementStatisticExport)
	protected.Get("/statistics/staff", h.StaffStatistic)
	protected.Get("/statistics/staff/export", h.StaffStatisticExport)
	protected.Get("/work-reports", h.WorkReports)
	protected.Get("/work-reports/summary", h.WorkReportSummary)
	protected.Get("/work-reports/export", h.ExportWorkReports)
	protected.Get("/work-reports/projects", h.WorkReportProjects)
	protected.Get("/work-reports/recipients", h.WorkReportRecipients)
	protected.Get("/work-reports/daily-reports/:id", h.WorkReportDetail)
	protected.Post("/work-reports/daily-reports/:id/submit", h.SubmitWorkReport)
	protected.Get("/work-reports/:id/revisions/:revision/evidence/:evidenceId/file", h.GetWorkReportEvidenceFile)
	protected.Post("/work-reports/:id/:action", h.ReviewWorkReport)
	protected.Get("/work-reports/:id/pdf", h.ExportWorkReportPDF)
	protected.Get("/reports/dashboard", h.Dashboard)
	protected.Get("/reports/dashboard/projects", h.DashboardProjects)
	protected.Get("/reports/dashboard/activities", h.DashboardActivities)
	protected.Get("/reports/options", h.ReportOptions)
	protected.Get("/reports/cashflow", h.CashflowReport)
	protected.Get("/reports/cashflow/export", h.CashflowReportCSV)
	protected.Get("/reports/tax", h.TaxReport)
	protected.Get("/reports/tax/export", h.TaxReportCSV)
	protected.Get("/reports/profit", h.ProfitReport)
	protected.Get("/reports/profit/export", h.ProfitReportCSV)
	protected.Get("/reports/projects", h.ProjectReport)
	protected.Get("/reports/projects/export", h.ProjectReportCSV)
	protected.Get("/reports/warehouse", h.WarehouseReport)
	protected.Get("/reports/warehouse/export", h.WarehouseReportCSV)
	protected.Get("/reports/procurement", h.ProcurementReport)
	protected.Get("/reports/procurement/export", h.ProcurementReportCSV)
	protected.Get("/reports/accounting", h.AccountingReport)
	protected.Get("/reports/accounting/export", h.AccountingReportCSV)
	protected.Get("/reports/staff", h.StaffReport)
	protected.Get("/reports/staff/export", h.StaffReportCSV)
}
