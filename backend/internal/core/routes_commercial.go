package core

import "github.com/gofiber/fiber/v2"

func registerCommercialRoutes(protected fiber.Router, h *Handler) {
	protected.Get("/projects/:id/boq", h.ProjectBOQ)
	protected.Post("/projects/:id/boq", h.CreateBOQ)
	protected.Get("/boq-items/:id", h.GetBOQ)
	protected.Put("/boq-items/:id", h.UpdateBOQ)
	protected.Post("/boq-items/:id/revise", h.ReviseBOQ)
	protected.Post("/boq-items/:id/unit-price/expected", h.UpdateBOQExpectedUnitPrice)
	protected.Post("/boq-items/:id/unit-price/lock-norm", h.LockBOQNormUnitPrice)
	protected.Post("/boq-items/:id/unit-price/lock-final", h.LockBOQFinalUnitPrice)
	protected.Post("/projects/:id/boq/submit", h.SubmitBOQ)
	protected.Post("/projects/:id/boq/approve", h.ApproveBOQ)
	protected.Post("/projects/:id/boq/generate-procurement", h.GenerateProcurementFromBOQ)
	protected.Get("/projects/:id/supplier-quotations", h.ProjectSupplierQuotations)
	protected.Post("/projects/:id/supplier-quotations", h.CreateSupplierQuotation)
	protected.Get("/projects/:id/supplier-quote-comparison", h.SupplierQuoteComparison)
	protected.Get("/supplier-quotations/:id", h.GetSupplierQuotation)
	protected.Put("/supplier-quotations/:id", h.UpdateSupplierQuotation)
	protected.Post("/supplier-quotations/:id/submit", h.SubmitSupplierQuotation)
	protected.Post("/supplier-quotations/:id/qualify", h.QualifySupplierQuotation)
	protected.Post("/supplier-quotation-items/:id/select", h.SelectSupplierQuote)
	protected.Get("/projects/:id/contracts", h.ProjectContracts)
	protected.Post("/projects/:id/contracts", h.CreateContract)
	protected.Get("/contracts/:id", h.GetContract)
	protected.Put("/contracts/:id", h.UpdateContract)
	protected.Post("/contracts/:id/versions", h.CreateContractVersion)
	protected.Post("/contract-versions/:id/submit", h.SubmitContractVersion)
	protected.Post("/contract-versions/:id/approve", h.ApproveContractVersion)
	protected.Post("/contract-versions/:id/sign", h.SignContractVersion)
	protected.Post("/contracts/:id/documents/upload", h.UploadContractDocument)
	protected.Post("/contracts/:id/dispatches", h.CreateContractDispatch)
	protected.Post("/contract-dispatches/:id/documents/upload", h.UploadContractDispatchDocument)
	protected.Post("/contract-dispatches/:id/receive", h.ReceiveContractDispatch)
	protected.Post("/contracts/:id/activate", h.ActivateContract)
	protected.Post("/contracts/:id/milestones", h.CreateContractMilestone)
	protected.Post("/contract-milestones/:id/eligible", h.EligibleContractMilestone)
	protected.Post("/contract-milestones/:id/open-obligation", h.OpenContractMilestoneObligation)
	protected.Post("/contracts/:id/variations", h.CreateContractVariation)
	protected.Post("/contract-variations/:id/submit", h.SubmitContractVariation)
	protected.Post("/contract-variations/:id/qs-review", h.QSReviewContractVariation)
	protected.Post("/contract-variations/:id/purchase", h.PurchaseContractVariation)
	protected.Post("/contract-variations/:id/approve", h.ApproveContractVariation)
	protected.Post("/contract-variations/:id/reject", h.RejectContractVariation)
	protected.Post("/contract-variations/:id/generate-procurement", h.GenerateContractVariationProcurement)
	protected.Post("/contract-variations/:id/incorporate", h.IncorporateContractVariation)
	protected.Post("/contract-retentions/:id/release", h.ReleaseContractRetention)
}
